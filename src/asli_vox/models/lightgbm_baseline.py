"""LightGBM Spoof Classifier and Acoustic Heuristic Baseline Stub.

This module attempts to load trained LightGBM weights from disk. If no weights
exist yet, it provides a clearly-commented acoustic heuristic baseline that evaluates
real spectral properties (high-frequency rolloff, vocoder artifacts, dynamic range)
to produce realistic bonafide/spoof confidence scores for the end-to-end demo.
"""
from pathlib import Path
from typing import Dict, Any, Optional
import numpy as np

from asli_vox.config import settings
from asli_vox.utils.logger import logger
from asli_vox.features.spectrogram import extract_acoustic_features

# Global model state
_MODEL = None
_MODEL_LOADED = False


def _try_load_model():
    """Attempt to load trained LightGBM model from configured paths."""
    global _MODEL, _MODEL_LOADED
    if _MODEL_LOADED:
        return _MODEL

    paths_to_check = [
        settings.MODEL_PATH,
        settings.FALLBACK_MODEL_PATH,
        Path(__file__).parent / "lgb_spoof_model.joblib",
        Path(__file__).parent / "lgb_model.joblib",
    ]

    for p in paths_to_check:
        if p.is_file():
            try:
                import joblib
                _MODEL = joblib.load(p)
                _MODEL_LOADED = True
                logger.info(f"Successfully loaded trained LightGBM model from {p}")
                return _MODEL
            except Exception as e:
                logger.warning(f"Failed loading model from {p}: {e}")

    logger.info("No trained LightGBM model file found. Using acoustic heuristic baseline stub.")
    return None


def is_model_loaded() -> bool:
    """Return True if a trained LightGBM model file was loaded."""
    _try_load_model()
    return _MODEL_LOADED


def extract_features_for_tabular(logmel: np.ndarray, audio: Optional[np.ndarray] = None, sr: int = 16000) -> np.ndarray:
    """
    Extract a compact 1D feature vector from (1, n_mels, time) log-mel spectrogram
    and time-domain audio suitable for LightGBM.
    """
    spec = logmel[0] if logmel.ndim == 3 else logmel  # (n_mels, time)

    # 1. Mel-band statistics across time
    mel_means = np.mean(spec, axis=1)  # (n_mels,)
    mel_stds = np.std(spec, axis=1)    # (n_mels,)
    mel_maxs = np.max(spec, axis=1)    # (n_mels,)
    mel_mins = np.min(spec, axis=1)    # (n_mels,)

    # 2. Time-frame statistics across mel bands
    time_means = np.mean(spec, axis=0)
    time_delta = np.diff(time_means) if len(time_means) > 1 else np.zeros(1)

    features = [
        mel_means,
        mel_stds,
        mel_maxs,
        mel_mins,
        np.array([
            np.mean(time_means),
            np.std(time_means),
            np.mean(np.abs(time_delta)),
            float(np.percentile(spec, 95) - np.percentile(spec, 5)),  # dynamic range
        ])
    ]

    # 3. Acoustic features
    if audio is not None and audio.size > 0:
        ac = extract_acoustic_features(audio, sr=sr)
        features.append(np.array(list(ac.values()), dtype=np.float32))

    return np.concatenate(features).astype(np.float32)


def heuristic_spoof_stub(logmel: np.ndarray, audio: Optional[np.ndarray] = None, sr: int = 16000) -> float:
    """
    Realistic acoustic heuristic baseline stub.

    Synthetic voices generated by neural vocoders (HiFi-GAN, WaveGlow, MelGAN)
    and acoustic models (VITS, FastSpeech, ElevenLabs) present consistent physical markers:
    1. Spectral dynamic range: Vocoder output has lower natural variance between silent/active frames.
    2. High-frequency mel distribution: Synthetic voices often have an unnatural energy plateau
       or sharp drop above 5 kHz due to 22.05kHz/24kHz upsampling.
    3. Spectral flatness: Natural speech has distinct vocal tract resonance formants;
       poorly-trained or over-smoothed TTS often has flatter spectral distribution.
    4. Energy variance: Deepfakes frequently show periodic micro-jitter or robotic constancy.

    Returns:
        float: Estimated spoof probability P(spoof) in [0.05, 0.95].
    """
    spec = logmel[0] if logmel.ndim == 3 else logmel  # (n_mels, time)
    n_mels, time_steps = spec.shape

    if time_steps < 3:
        # Neutral if audio is too short
        return 0.50

    # Marker 1: High-to-Low mel band energy ratio
    # Lower bands (0 to n_mels//2) represent fundamental frequencies and formants
    # Upper bands (n_mels*3//4 to n_mels) capture high-frequency harmonics and noise
    low_band = spec[: n_mels // 3, :]
    mid_band = spec[n_mels // 3 : 2 * n_mels // 3, :]
    high_band = spec[2 * n_mels // 3 :, :]

    low_mean = float(np.mean(low_band))
    high_mean = float(np.mean(high_band))
    band_ratio = high_mean / (low_mean - 1e-5)

    # Marker 2: Dynamic range (in dB)
    p95 = float(np.percentile(spec, 95))
    p05 = float(np.percentile(spec, 5))
    dyn_range = p95 - p05

    # Marker 3: Temporal frame variability (vocal tract movement)
    frame_energy = np.mean(spec, axis=0)
    temporal_variance = float(np.var(frame_energy))

    # Marker 4: Spectral flatness across time
    time_diffs = np.diff(spec, axis=1)
    smoothness = float(np.mean(np.abs(time_diffs)))

    # Compute spoof indicator score
    # Balanced baseline centering around 0.5
    raw_score = 0.0

    # Natural speech typically has dyn_range > 50 dB; compressed TTS often has < 40 dB
    if dyn_range < 40.0:
        raw_score += 0.25
    elif dyn_range > 55.0:
        raw_score -= 0.25

    # Natural speech has high temporal variance (> 25); robotic flat speech has low variance
    if temporal_variance < 15.0:
        raw_score += 0.20
    elif temporal_variance > 35.0:
        raw_score -= 0.20

    # High frequency ratio anomalies
    if band_ratio > 0.85:
        raw_score += 0.20
    elif band_ratio < 0.60:
        raw_score -= 0.15

    # Smoothness anomaly (vocoder over-smoothing)
    if smoothness < 3.0:
        raw_score += 0.15
    elif smoothness > 6.0:
        raw_score -= 0.10

    # Map to probability via sigmoid
    spoof_prob = 1.0 / (1.0 + np.exp(-raw_score))
    # Keep within realistic bounds [0.08, 0.94] so confidence is never 100% or 0%
    spoof_prob = float(np.clip(spoof_prob, 0.08, 0.94))
    return spoof_prob


def classify(logmel: np.ndarray, audio: Optional[np.ndarray] = None, sr: int = 16000) -> Dict[str, Any]:
    """
    Classify audio as 'bonafide' (genuine) or 'spoof' (AI-generated/deepfake).

    Returns:
        dict with:
            - verdict: "bonafide" or "spoof"
            - confidence: float in [0.50, 1.00]
            - spoof_probability: float in [0.0, 1.0]
            - model_source: "lightgbm_weights" or "heuristic_baseline"
    """
    model = _try_load_model()

    if model is not None:
        try:
            feat_vec = extract_features_for_tabular(logmel, audio, sr).reshape(1, -1)
            if hasattr(model, "predict_proba"):
                probs = model.predict_proba(feat_vec)[0]
                # Assuming index 1 corresponds to spoof
                spoof_prob = float(probs[1]) if len(probs) > 1 else float(probs[0])
            elif hasattr(model, "predict"):
                pred = model.predict(feat_vec)
                spoof_prob = float(pred[0])
            else:
                spoof_prob = heuristic_spoof_stub(logmel, audio, sr)
            source = "lightgbm_weights"
        except Exception as e:
            logger.warning(f"Inference error on trained model: {e}. Falling back to heuristic stub.")
            spoof_prob = heuristic_spoof_stub(logmel, audio, sr)
            source = "heuristic_baseline"
    else:
        spoof_prob = heuristic_spoof_stub(logmel, audio, sr)
        source = "heuristic_baseline"

    # Verdict and confidence mapping
    is_spoof = spoof_prob >= 0.50
    verdict = "spoof" if is_spoof else "bonafide"
    confidence = spoof_prob if is_spoof else (1.0 - spoof_prob)

    return {
        "verdict": verdict,
        "confidence": round(float(confidence), 4),
        "spoof_probability": round(float(spoof_prob), 4),
        "model_source": source,
    }
